'use strict';

const os = require('node:os');
const path = require('node:path');
const fs = require('node:fs');

const APP_DIR_NAME = 'adblock-launcher';

/** Root data directory, overridable for tests. */
function dataRoot() {
  const base = process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local', 'share');
  return path.join(base, APP_DIR_NAME);
}

const paths = {
  appDir: () => dataRoot(),
  /** Named sets of sites. */
  profilesFile: () => path.join(dataRoot(), 'profiles.json'),
  /** Pre-profiles format; read once on first run, then left as a backup. */
  sitesFile: () => path.join(dataRoot(), 'sites.json'),
  /**
   * Live TV channels.
   *
   * Deliberately not per-profile: the channels are the same for everyone, and
   * duplicating 453 records per profile would be storage with no meaning behind
   * it. Kept out of profiles.json too, because the sites list validates its
   * entries as web addresses and a stream URL is not one.
   */
  channelsFile: () => path.join(dataRoot(), 'channels.json'),
  /**
   * Which channels were last seen working. Generated by the health check and
   * merged over the master list at read time, so re-probing never rewrites the
   * user's own research file.
   */
  channelHealthFile: () => path.join(dataRoot(), 'channel-health.json'),
  /**
   * Settings. Deliberately not in profiles.json: a profile is "whose apps are
   * these", a setting is "how this launcher behaves", and they get out of step.
   */
  settingsFile: () => path.join(dataRoot(), 'settings.json'),
  iconsDir: () => path.join(dataRoot(), 'icons'),
  cacheDir: () => path.join(dataRoot(), 'cache'),
  /** Scratch space for browser state that must not live beside user data. */
  runtimeDir: () => path.join(dataRoot(), 'runtime'),

  /** Create every directory the app writes to. */
  ensure() {
    for (const dir of [paths.appDir(), paths.iconsDir(), paths.cacheDir(), paths.runtimeDir()]) {
      fs.mkdirSync(dir, { recursive: true });
    }
    return paths;
  },
};

module.exports = { paths, APP_DIR_NAME };